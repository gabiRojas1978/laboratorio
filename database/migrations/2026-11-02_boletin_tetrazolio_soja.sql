CREATE TABLE IF NOT EXISTS boletines_tetrazolio_soja (
    id_boletin_tetrazolio_soja INT AUTO_INCREMENT PRIMARY KEY,
    id_empresa INT NOT NULL,
    id_cliente INT NOT NULL,
    id_usuario INT NULL,
    id_especie INT UNSIGNED NOT NULL,
    muestra_nro VARCHAR(100) NOT NULL,
    nro_interno VARCHAR(100) NULL,
    nro_certificado VARCHAR(100) NULL,
    nombre_solicitante VARCHAR(255) NULL,
    precinto_muestra VARCHAR(100) NULL,
    procedencia VARCHAR(255) NULL,
    fecha_recepcion DATE NULL,
    fecha_analisis DATE NULL,
    analista VARCHAR(150) NULL,
    cultivar VARCHAR(150) NULL,
    semillas_evaluadas SMALLINT UNSIGNED NOT NULL DEFAULT 200,
    concentracion_tz VARCHAR(100) NULL,
    tiempo_tincion VARCHAR(100) NULL,
    temperatura_tincion VARCHAR(100) NULL,
    rep_mayor_menor VARCHAR(100) NULL,
    tolerancia_tabla VARCHAR(100) NULL,
    observaciones TEXT NULL,
    created_at_boletin TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_boletin_tetrazolio_soja_empresa_cliente (id_empresa, id_cliente),
    CONSTRAINT fk_boletin_tetrazolio_soja_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresas(id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_boletin_tetrazolio_soja_cliente FOREIGN KEY (id_cliente)
        REFERENCES clientes(id_cliente) ON DELETE CASCADE,
    CONSTRAINT fk_boletin_tetrazolio_soja_especie FOREIGN KEY (id_especie)
        REFERENCES especies(id_especie) ON DELETE RESTRICT,
    CONSTRAINT fk_boletin_tetrazolio_soja_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios(id_usuario) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

